-- Isolated development schema for the mobile application.
-- This file does not copy or mutate data in public.

CREATE SCHEMA IF NOT EXISTS working;

CREATE TABLE working.units (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(16) NOT NULL UNIQUE,
  name VARCHAR(64) NOT NULL UNIQUE,
  decimal_places SMALLINT NOT NULL DEFAULT 2 CHECK (decimal_places BETWEEN 0 AND 4),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE working.item_grades (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(16) NOT NULL UNIQUE,
  name VARCHAR(64) NOT NULL UNIQUE,
  sort_order SMALLINT NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE working.items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(32) NOT NULL UNIQUE,
  name VARCHAR(255) NOT NULL UNIQUE,
  primary_unit_id BIGINT NOT NULL REFERENCES working.units(id) ON DELETE RESTRICT,
  secondary_unit_id BIGINT REFERENCES working.units(id) ON DELETE RESTRICT,
  inventory_unit_id BIGINT NOT NULL REFERENCES working.units(id) ON DELETE RESTRICT,
  default_kg_per_crate NUMERIC(8,2) CHECK (default_kg_per_crate > 0),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (secondary_unit_id IS NULL OR secondary_unit_id <> primary_unit_id)
);

CREATE TABLE working.item_variants (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id BIGINT NOT NULL REFERENCES working.items(id) ON DELETE RESTRICT,
  grade_id BIGINT NOT NULL REFERENCES working.item_grades(id) ON DELETE RESTRICT,
  variant_code VARCHAR(64) NOT NULL UNIQUE,
  name VARCHAR(255) NOT NULL UNIQUE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (item_id, grade_id)
);

