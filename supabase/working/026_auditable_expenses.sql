-- Auditable operating expenses for a configurable single-trader deployment.

CREATE TABLE working.expense_categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(32) NOT NULL UNIQUE
    CHECK (code ~ '^[A-Z][A-Z0-9_-]{1,31}$'),
  name VARCHAR(80) NOT NULL CHECK (btrim(name) <> ''),
  sort_order SMALLINT NOT NULL DEFAULT 100 CHECK (sort_order >= 0),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX uq_expense_category_normalized_name
  ON working.expense_categories (lower(regexp_replace(btrim(name), '\s+', ' ', 'g')));

CREATE TABLE working.expenses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  expense_date DATE NOT NULL DEFAULT CURRENT_DATE,
  category_id BIGINT NOT NULL REFERENCES working.expense_categories(id) ON DELETE RESTRICT,
  amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
  payment_method VARCHAR(20) NOT NULL DEFAULT 'cash'
    CHECK (payment_method IN ('cash', 'bank_transfer', 'upi', 'cheque', 'other')),
  payee VARCHAR(160),
  reference_number VARCHAR(120),
  notes TEXT,
  created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  voided_at TIMESTAMPTZ,
  voided_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  void_reason TEXT,
  CHECK (
    (voided_at IS NULL AND voided_by IS NULL AND void_reason IS NULL)
    OR
    (voided_at IS NOT NULL AND void_reason IS NOT NULL AND btrim(void_reason) <> '')
  )
);

CREATE INDEX idx_expenses_active_date
  ON working.expenses (expense_date DESC, id DESC)
  WHERE voided_at IS NULL;

CREATE UNIQUE INDEX uq_expense_non_cash_reference
  ON working.expenses (payment_method, lower(btrim(reference_number)))
  WHERE reference_number IS NOT NULL AND voided_at IS NULL;

