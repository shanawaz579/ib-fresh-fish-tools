CREATE OR REPLACE FUNCTION working.assert_stock_delta_available(
  p_item_variant_id BIGINT,
  p_location_id BIGINT,
  p_crates_delta INTEGER,
  p_kg_delta NUMERIC
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = working
AS $$
DECLARE
  current_crates BIGINT;
  current_kg NUMERIC(14,2);
BEGIN
  PERFORM pg_advisory_xact_lock(
    hashtextextended('working-stock:' || p_location_id::TEXT || ':' || p_item_variant_id::TEXT, 0)
  );

  SELECT coalesce(sum(crates_delta), 0), coalesce(sum(kg_delta), 0)
  INTO current_crates, current_kg
  FROM working.stock_movements
  WHERE item_variant_id = p_item_variant_id
    AND location_id = p_location_id
    AND voided_at IS NULL;

  IF current_crates + p_crates_delta < 0 THEN
    RAISE EXCEPTION 'Insufficient crate stock. Available: %, requested: %',
      current_crates, abs(p_crates_delta);
  END IF;

  IF current_kg + p_kg_delta < 0 THEN
    RAISE EXCEPTION 'Insufficient kilogram stock. Available: %, requested: %',
      current_kg, abs(p_kg_delta);
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION working.sync_source_stock_movement()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = working
AS $$
DECLARE
  default_location_id BIGINT;
  source_kind TEXT := CASE WHEN TG_TABLE_NAME = 'purchases' THEN 'purchase' ELSE 'sale' END;
  variant_id BIGINT;
  record_id BIGINT;
  record_date DATE;
  crates_value INTEGER;
  kg_value NUMERIC;
  old_crates_delta INTEGER;
  old_kg_delta NUMERIC;
BEGIN
  SELECT id INTO default_location_id
  FROM working.stock_locations
  WHERE code = 'MAIN' AND is_active;

  IF default_location_id IS NULL THEN
    RAISE EXCEPTION 'Main stock location is unavailable';
  END IF;

  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    SELECT crates_delta, kg_delta
    INTO old_crates_delta, old_kg_delta
    FROM working.stock_movements
    WHERE source_type = source_kind
      AND source_id = OLD.id
      AND voided_at IS NULL
    FOR UPDATE;

    IF TG_OP = 'DELETE' AND (coalesce(old_crates_delta, 0) > 0 OR coalesce(old_kg_delta, 0) > 0) THEN
      PERFORM working.assert_stock_delta_available(
        OLD.fish_variety_id,
        default_location_id,
        -coalesce(old_crates_delta, 0),
        -coalesce(old_kg_delta, 0)
      );
    END IF;

    UPDATE working.stock_movements
    SET voided_at = now(),
        void_reason = CASE WHEN TG_OP = 'DELETE' THEN 'Source record deleted' ELSE 'Source record changed' END
    WHERE source_type = source_kind
      AND source_id = OLD.id
      AND voided_at IS NULL;
  END IF;

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;

  record_id := NEW.id;
  variant_id := NEW.fish_variety_id;
  crates_value := NEW.quantity_crates;

  IF source_kind = 'purchase' THEN
    record_date := NEW.purchase_date;
    kg_value := NEW.quantity_kg;
  ELSE
    record_date := NEW.sale_date;
    crates_value := -crates_value;
    kg_value := -NEW.quantity_kg;
  END IF;

  PERFORM working.assert_stock_delta_available(
    variant_id, default_location_id, crates_value, kg_value
  );

  INSERT INTO working.stock_movements (
    movement_date, location_id, item_variant_id, movement_type,
    crates_delta, kg_delta, source_type, source_id, reason, created_by
  ) VALUES (
    record_date, default_location_id, variant_id, source_kind,
    crates_value, kg_value, source_kind, record_id,
    CASE WHEN source_kind = 'purchase' THEN 'Purchase stock received' ELSE 'Customer sale dispatched' END,
    auth.uid()
  );

  RETURN NEW;
END;
$$;

