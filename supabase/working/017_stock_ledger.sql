-- Cumulative, auditable inventory ledger with source synchronization and reconciliation.

CREATE TABLE working.stock_locations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(32) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

INSERT INTO working.stock_locations (code, name)
VALUES ('MAIN', 'Main stock')
ON CONFLICT (code) DO NOTHING;

CREATE TABLE working.stock_movements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  movement_date DATE NOT NULL,
  location_id BIGINT NOT NULL REFERENCES working.stock_locations(id) ON DELETE RESTRICT,
  item_variant_id BIGINT NOT NULL REFERENCES working.item_variants(id) ON DELETE RESTRICT,
  movement_type VARCHAR(32) NOT NULL CHECK (movement_type IN (
    'opening', 'purchase', 'sale', 'adjustment_in', 'adjustment_out',
    'wastage', 'sale_return', 'purchase_return', 'reconciliation'
  )),
  crates_delta INTEGER NOT NULL DEFAULT 0,
  kg_delta NUMERIC(12,2) NOT NULL DEFAULT 0,
  source_type VARCHAR(24) CHECK (source_type IN ('purchase', 'sale', 'manual')),
  source_id BIGINT,
  reason VARCHAR(255),
  notes TEXT,
  created_by UUID,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  voided_at TIMESTAMPTZ,
  voided_by UUID,
  void_reason TEXT,
  CHECK (crates_delta <> 0 OR kg_delta <> 0),
  CHECK (
    (movement_type IN ('opening', 'purchase', 'adjustment_in', 'sale_return')
      AND crates_delta >= 0 AND kg_delta >= 0)
    OR (movement_type IN ('sale', 'adjustment_out', 'wastage', 'purchase_return')
      AND crates_delta <= 0 AND kg_delta <= 0)
    OR movement_type = 'reconciliation'
  ),
  CHECK (
    (source_type IN ('purchase', 'sale') AND source_id IS NOT NULL)
    OR source_type = 'manual'
  )
);

CREATE UNIQUE INDEX uq_active_stock_source_movement
  ON working.stock_movements(source_type, source_id)
  WHERE source_type IN ('purchase', 'sale') AND voided_at IS NULL;

CREATE INDEX idx_stock_movements_variant_location_date
  ON working.stock_movements(item_variant_id, location_id, movement_date, id)
  WHERE voided_at IS NULL;

CREATE INDEX idx_stock_movements_recent
  ON working.stock_movements(movement_date DESC, id DESC);

ALTER TABLE working.stock_locations ENABLE ROW LEVEL SECURITY;
ALTER TABLE working.stock_movements ENABLE ROW LEVEL SECURITY;

