CREATE TABLE working.cash_adjustments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_date DATE NOT NULL DEFAULT CURRENT_DATE,
  direction VARCHAR(3) NOT NULL CHECK (direction IN ('in', 'out')),
  amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
  reason VARCHAR(180) NOT NULL CHECK (char_length(btrim(reason)) >= 3),
  reference_number VARCHAR(120),
  created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  voided_at TIMESTAMPTZ,
  voided_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  void_reason TEXT,
  CHECK (
    (voided_at IS NULL AND voided_by IS NULL AND void_reason IS NULL)
    OR
    (voided_at IS NOT NULL AND void_reason IS NOT NULL AND btrim(void_reason) <> '')
  )
);

CREATE TABLE working.cash_day_closings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_date DATE NOT NULL,
  opening_cash NUMERIC(14,2) NOT NULL,
  cash_received NUMERIC(14,2) NOT NULL DEFAULT 0,
  cash_supplier_payments NUMERIC(14,2) NOT NULL DEFAULT 0,
  cash_expenses NUMERIC(14,2) NOT NULL DEFAULT 0,
  cash_adjustments_in NUMERIC(14,2) NOT NULL DEFAULT 0,
  cash_adjustments_out NUMERIC(14,2) NOT NULL DEFAULT 0,
  expected_closing_cash NUMERIC(14,2) NOT NULL,
  counted_cash NUMERIC(14,2) NOT NULL CHECK (counted_cash >= 0),
  difference NUMERIC(14,2) GENERATED ALWAYS AS (counted_cash - expected_closing_cash) STORED,
  notes TEXT,
  closed_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  closed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  voided_at TIMESTAMPTZ,
  voided_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  void_reason TEXT,
  CHECK (
    (voided_at IS NULL AND voided_by IS NULL AND void_reason IS NULL)
    OR
    (voided_at IS NOT NULL AND void_reason IS NOT NULL AND btrim(void_reason) <> '')
  )
);

CREATE UNIQUE INDEX uq_active_cash_day_closing
  ON working.cash_day_closings (business_date)
  WHERE voided_at IS NULL;
CREATE INDEX idx_cash_adjustments_active_date
  ON working.cash_adjustments (business_date DESC, id DESC)
  WHERE voided_at IS NULL;
CREATE INDEX idx_cash_day_closings_date
  ON working.cash_day_closings (business_date DESC, id DESC);

ALTER TABLE working.cash_adjustments ENABLE ROW LEVEL SECURITY;
ALTER TABLE working.cash_day_closings ENABLE ROW LEVEL SECURITY;

