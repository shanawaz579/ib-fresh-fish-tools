GRANT EXECUTE ON FUNCTION working.get_cashbook_day(DATE) TO authenticated;
REVOKE ALL ON FUNCTION working.record_cash_adjustment(DATE, VARCHAR, NUMERIC, TEXT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION working.record_cash_adjustment(DATE, VARCHAR, NUMERIC, TEXT, TEXT) TO authenticated;
REVOKE ALL ON FUNCTION working.void_cash_adjustment(BIGINT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION working.void_cash_adjustment(BIGINT, TEXT) TO authenticated;
REVOKE ALL ON FUNCTION working.close_cash_day(DATE, NUMERIC, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION working.close_cash_day(DATE, NUMERIC, TEXT) TO authenticated;
REVOKE ALL ON FUNCTION working.reopen_cash_day(BIGINT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION working.reopen_cash_day(BIGINT, TEXT) TO authenticated;

COMMENT ON TABLE working.cash_day_closings IS
  'Immutable daily cash snapshots. Reopening voids a snapshot while preserving its audit history.';
COMMENT ON VIEW working.cashbook_entries IS
  'Unified cash-only ledger sourced from customer receipts, supplier payments, expenses, and adjustments.';

COMMIT;
