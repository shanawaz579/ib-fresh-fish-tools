  END IF;

  RETURN jsonb_build_object(
    'correction_id', correction_id_value,
    'supplier_id', target_bill.supplier_id,
    'bill_date', target_bill.bill_date,
    'original_bill_number', target_bill.bill_number
  );
END;
$$;

