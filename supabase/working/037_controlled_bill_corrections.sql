  SELECT bill.*
  INTO target_bill
  FROM working.purchase_bills bill
  WHERE bill.id = p_purchase_bill_id
  FOR UPDATE;

  IF NOT FOUND THEN RAISE EXCEPTION 'Purchase bill not found'; END IF;
